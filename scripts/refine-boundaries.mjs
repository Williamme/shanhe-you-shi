for (const [id, definition] of Object.entries(polygons)) {
  const features = [];
  if (definition.features) {
    for (const feature of definition.features) {
      features.push(makeFeature({
        name: feature.name,
        color: feature.color,
        role: feature.role || "primary",
        coordinates: feature.rings.length === 1 ? feature.rings[0] : feature.rings
      }, feature.rings.length > 1));
    }
  } else {
    features.push(makeFeature({
      name: definition.name,
      color: definition.color,
      role: "primary",
      coordinates: definition.rings.length === 1 ? definition.rings[0] : definition.rings
    }, definition.rings.length > 1));
    for (const extra of definition.extra || []) {
      features.push(makeFeature({
        name: extra.name,
        color: definition.color,
        role: extra.role || "primary",
        coordinates: extra.coordinates
      }, false));
    }
  }

  const output = { type: "FeatureCollection", features };
  fs.writeFileSync(path.join(geoDir, `${id}.geojson`), `${JSON.stringify(output, null, 2)}\n`, "utf8");
}

function makeFeature({ name, color, role, coordinates }, multi) {
  return {
    type: "Feature",
    properties: { name, role, color },
    geometry: {
      type: multi ? "MultiPolygon" : "Polygon",
      coordinates: multi ? coordinates.map((ring) => [ring]) : [coordinates]
    }
  };
}

